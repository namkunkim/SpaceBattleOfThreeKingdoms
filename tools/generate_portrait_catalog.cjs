// Rebuild runtime assets and ID mapping from the current approved portrait manifest.
const fs=require('fs'),path=require('path');
const root=path.resolve(__dirname,'..'),source=path.join(root,'output/seonghanji-portraits-distinct-20261017');
const m=JSON.parse(fs.readFileSync(path.join(source,'manifest.json'))),characters=JSON.parse(fs.readFileSync(process.argv[2]||'C:/WorkSpace/Seonghanji/data/characters.json'));
const dest=path.join(root,'assets/portraits/seonghanji');fs.mkdirSync(dest,{recursive:true});
const legacy=['유비','관우','제갈량','조운','조조','장비'];
const records=[...legacy.map(name=>m.records.find(r=>r.name===name)),...m.records.filter(r=>!legacy.includes(r.name))];
const byShj={},byName={},byCharacter={},entries=[];
for(const [index,r]of records.entries()){
 if(r.status!=='generated')throw Error('Portrait pending '+r.id);
 const file=path.join(source,'images',r.filename),bytes=fs.readFileSync(file);
 if(bytes.readUInt32BE(16)!==561||bytes.readUInt32BE(20)!==701)throw Error('Portrait dimensions '+r.id);
 fs.copyFileSync(file,path.join(dest,r.filename));byShj[r.id]=index;
 if(m.records.filter(x=>x.name===r.name).length===1)byName[r.name]=index;
 entries.push({index,id:r.id,name:r.name,faction:r.faction,path:'res://assets/portraits/seonghanji/'+r.filename,character_ids:[]});
}
const aliases={'CHR-0142':'관색','CHR-0249':'육모','CHR-0313':'장횡(동탁·여포)','CHR-0351':'장횡(서량)','CHR-0425':'유기'};
const unresolved=[];
for(const c of characters){let matches=m.records.filter(r=>r.name===(aliases[c.id]||c.name));
 if(matches.length>1){const faction=c.id==='CHR-0425'?'동이권 — 백제':c.origin_faction.replace(/^군웅·/,'');matches=matches.filter(r=>r.faction.startsWith(faction));}
 if(matches.length!==1){unresolved.push({id:c.id,name:c.name,reason:matches.length?'Ambiguous individual':'No individual portrait for composite or unnamed group'});continue;}
 const index=byShj[matches[0].id];byCharacter[c.id]=index;entries[index].character_ids.push(c.id);
 if(characters.filter(other=>other.name===c.name).length===1)byName[c.name]=index;
}
const gd='# Generated by tools/generate_portrait_catalog.cjs. Keep the first six legacy UI indices stable.\nextends RefCounted\n\nconst BY_CHARACTER_ID := '+JSON.stringify(byCharacter,null,'\t')+'\n\nconst BY_NAME := '+JSON.stringify(byName,null,'\t')+'\n\nconst BY_PORTRAIT_ID := '+JSON.stringify(byShj,null,'\t')+'\n\nconst PATHS := '+JSON.stringify(entries.map(r=>r.path),null,'\t')+'\n';
fs.writeFileSync(path.join(dest,'catalog.gd'),gd);
fs.writeFileSync(path.join(dest,'catalog.json'),JSON.stringify({source:'output/seonghanji-portraits-distinct-20261017/manifest.json',total:entries.length,matchedCharacterIds:Object.keys(byCharacter).length,unresolved,entries},null,2));
console.log(JSON.stringify({portraits:entries.length,matchedCharacterIds:Object.keys(byCharacter).length,unresolved}));
